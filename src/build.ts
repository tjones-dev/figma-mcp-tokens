// Builds the outputs from tokens.json: CSS custom properties and a JS/TS module. Values are
// resolved (primitives aren't output, so nothing can refer to them in CSS). The first mode
// of every collection is the default; each other mode is written as the tokens whose value
// differs in it, under css.modeSelector and in the module's $modes.
import type { Config } from "./config.js";
import { EXT, STYLE_GROUPS, type Group, type Token } from "./dtcg.js";
import type { Issues } from "./issues.js";

export type OutputFile = { path: string; content: string };

type Entry = { path: string[]; token: Token };

const HEADER = "Generated by figma-mcp-tokens from tokens.json; never edit by hand.";
const NUMERIC = ["dimension", "duration", "number"];
const TYPES = [...NUMERIC, "color", "string", "boolean", "typography", "shadow"];

const isReference = (value: unknown): value is string =>
  typeof value === "string" && /^\{[^{}]+\}$/.test(value);

/** Every token in tokens.json, in order. */
function entries(tokens: Group, issues: Issues): Entry[] {
  const found: Entry[] = [];
  const walk = (group: Group, path: string[]) => {
    for (const [key, node] of Object.entries(group)) {
      if (key.startsWith("$") || typeof node !== "object" || node === null) continue;
      if (!("$value" in node)) {
        walk(node as Group, [...path, key]);
        continue;
      }
      const token = node as Token;
      if (!TYPES.includes(token.$type)) {
        issues.add(`${[...path, key].join(".")}: $type ${String(token.$type)} isn't supported.`);
        continue;
      }
      found.push({ path: [...path, key], token });
    }
  };
  walk(tokens, []);
  return found;
}

/** Mode names past each collection's first, in order. */
function modeNames(tokens: Group, all: Entry[]): string[] {
  const names = new Set<string>();
  for (const group of Object.values(tokens)) {
    const modes = ((group as Group)?.["$extensions"] as Token["$extensions"])?.[EXT]?.["modes"];
    if (Array.isArray(modes)) modes.slice(1).forEach((m) => names.add(String(m)));
  }
  for (const { token } of all) {
    Object.keys(token.$extensions?.[EXT]?.["modes"] ?? {}).forEach((m) => names.add(m));
  }
  return [...names];
}

/** A dimension, duration or number as a number: px, ms or unitless (rem is 16px). */
function numeric(value: unknown, where: string): number {
  if (typeof value === "number") return value;
  const match = typeof value === "string" ? /^(-?[\d.]+)(px|rem|ms)?$/.exec(value) : null;
  if (!match) throw new Error(`${where}: ${JSON.stringify(value)} isn't a number.`);
  return Number(match[1]) * (match[2] === "rem" ? 16 : 1);
}

/** A value of one numeric type written as another. */
function convert(value: unknown, from: string, to: string, where: string): unknown {
  if (from === to) return value;
  if (NUMERIC.includes(from) && NUMERIC.includes(to)) {
    const n = numeric(value, where);
    return to === "dimension" ? `${n}px` : to === "duration" ? `${n}ms` : n;
  }
  throw new Error(`${where}: a ${to} token can't refer to a ${from} token.`);
}

class Resolver {
  private readonly byPath = new Map<string, Entry>();

  constructor(all: Entry[]) {
    for (const entry of all) this.byPath.set(entry.path.join("."), entry);
  }

  /** The value of a token in a mode (null for the default), with every reference resolved. */
  resolve(entry: Entry, mode: string | null, seen: string[] = []): unknown {
    const where = entry.path.join(".");
    if (seen.includes(where)) throw new Error(`${where}: circular reference (${[...seen, where].join(" → ")}).`);
    const modes = entry.token.$extensions?.[EXT]?.["modes"] as Record<string, unknown> | undefined;
    const raw = mode !== null && modes?.[mode] !== undefined ? modes[mode] : entry.token.$value;
    const trail = [...seen, where];

    if (isReference(raw)) return this.reference(raw, entry.token.$type, mode, trail);
    if (entry.token.$type === "typography") {
      const value = raw as Record<string, unknown>;
      const field = (name: string, type: string) =>
        isReference(value[name]) ? this.reference(value[name] as string, type, mode, trail) : value[name];
      return {
        ...value,
        fontFamily: field("fontFamily", "string"),
        fontWeight: field("fontWeight", "number"),
        fontSize: field("fontSize", "dimension"),
        lineHeight: field("lineHeight", "lineHeight"),
        letterSpacing: field("letterSpacing", "dimension"),
      };
    }
    if (entry.token.$type === "shadow") {
      const layers = Array.isArray(raw) ? raw : [raw];
      return layers.map((layer: Record<string, unknown>) => {
        const field = (name: string, type: string) =>
          isReference(layer[name]) ? this.reference(layer[name] as string, type, mode, trail) : layer[name];
        return {
          ...layer,
          color: field("color", "color"),
          offsetX: field("offsetX", "dimension"),
          offsetY: field("offsetY", "dimension"),
          blur: field("blur", "dimension"),
          spread: field("spread", "dimension"),
        };
      });
    }
    return raw;
  }

  /** The value a reference points at, as `type` ("lineHeight": a number stays unitless). */
  private reference(ref: string, type: string, mode: string | null, seen: string[]): unknown {
    const where = seen.at(-1) ?? "";
    const target = this.byPath.get(ref.slice(1, -1));
    if (!target) throw new Error(`${where}: ${ref} points at no token.`);
    const value = this.resolve(target, mode, seen);
    if (type === "lineHeight") return target.token.$type === "number" ? value : convert(value, target.token.$type, "dimension", where);
    return convert(value, target.token.$type, type, where);
  }
}

const kebab = (part: string) =>
  part
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

/** The token's path in the outputs: without its collection, but text styles keep `text`. */
const outPath = ({ path }: Entry) => (path[0] === "text" ? path : path.slice(1));

/** The custom property name without `--`: the WEB code syntax, or the output path in kebab-case. */
function cssName(entry: Entry, prefix: string, issues: Issues): string {
  const web = (entry.token.$extensions?.["com.figma"]?.["codeSyntax"] as { WEB?: unknown } | undefined)?.WEB;
  let name = outPath(entry).map(kebab).filter(Boolean).join("-");
  if (typeof web === "string") {
    const match = /^(?:var\()?--([A-Za-z0-9_-]+)\)?$/.exec(web.trim());
    if (match?.[1]) name = match[1];
    else issues.add(`${entry.path.join(".")}: WEB code syntax ${web} isn't a CSS custom property; using --${name}.`);
  }
  return prefix ? `${prefix}-${name}` : name;
}

const px = (value: unknown) => (typeof value === "number" ? `${value}px` : String(value));
const cssString = (value: unknown) => String(value);
/** A family name, quoted unless it's a single identifier. */
const fontFamily = (family: unknown) => {
  const name = String(family);
  return /^[A-Za-z][A-Za-z0-9-]*$/.test(name) ? name : `"${name.replace(/"/g, '\\"')}"`;
};
const isZero = (value: unknown) => value === undefined || /^0(px|em|rem)?$/.test(String(value));

/** The custom properties for a resolved value: [suffix, value] pairs. */
function cssValues(type: string, value: unknown): [string, string][] {
  if (type === "typography") {
    const v = value as Record<string, unknown>;
    const style = v["fontStyle"] === "italic" ? "italic " : "";
    // Letter spacing, transform and decoration only when they aren't the default.
    const values: [string, string][] = [
      ["", `${style}${v["fontWeight"]} ${px(v["fontSize"])}/${cssString(v["lineHeight"])} ${fontFamily(v["fontFamily"])}`],
    ];
    if (!isZero(v["letterSpacing"])) values.push(["-letter-spacing", px(v["letterSpacing"])]);
    if ((v["textTransform"] ?? "none") !== "none") values.push(["-text-transform", cssString(v["textTransform"])]);
    if ((v["textDecoration"] ?? "none") !== "none") values.push(["-text-decoration", cssString(v["textDecoration"])]);
    return values;
  }
  if (type === "shadow") {
    const layers = value as Record<string, unknown>[];
    const shadow = layers
      .map((l) =>
        [l["inset"] ? "inset" : "", px(l["offsetX"]), px(l["offsetY"]), px(l["blur"]), px(l["spread"]), l["color"]]
          .filter(Boolean)
          .join(" "),
      )
      .join(", ");
    return [["", shadow || "none"]];
  }
  if (type === "dimension") return [["", px(value)]];
  if (type === "duration") return [["", typeof value === "number" ? `${value}ms` : String(value)]];
  return [["", String(value)]];
}

/** A resolved value as the module holds it: px and ms as numbers, shadows as CSS. */
function moduleValue(type: string, value: unknown): unknown {
  const number = (v: unknown, unit: string) =>
    typeof v === "string" && new RegExp(`^-?[\\d.]+${unit}$`).test(v) ? Number.parseFloat(v) : v;
  if (type === "dimension") return number(value, "px");
  if (type === "duration") return number(value, "ms");
  if (type === "typography") {
    const v = value as Record<string, unknown>;
    return { ...v, fontSize: number(v["fontSize"], "px") };
  }
  if (type === "shadow") return cssValues(type, value)[0]?.[1];
  return value;
}

function setPath(root: Record<string, unknown>, path: string[], value: unknown): boolean {
  let group = root;
  for (const key of path.slice(0, -1)) {
    const next = (group[key] ??= {}) as Record<string, unknown>;
    if (typeof next !== "object" || next === null) return false;
    group = next;
  }
  const last = path.at(-1) ?? "";
  if (last in group) return false;
  group[last] = value;
  return true;
}

const sameValue = (a: unknown, b: unknown) => JSON.stringify(a) === JSON.stringify(b);

/** The CSS and module files for tokens.json, per the config. */
export function buildOutputs(tokens: Group, config: Config, issues: Issues): OutputFile[] {
  const all = entries(tokens, issues);
  const resolver = new Resolver(all);
  const modes = modeNames(tokens, all);
  const output = all.filter(({ path }) => !config.primitives.includes(path[0] ?? "") || STYLE_GROUPS.includes(path[0] ?? ""));

  type Resolved = { entry: Entry; name: string; value: unknown; modes: Map<string, unknown> };
  const resolved: Resolved[] = [];
  const names = new Map<string, string>();
  for (const entry of output) {
    const where = entry.path.join(".");
    let value: unknown;
    try {
      value = resolver.resolve(entry, null);
    } catch (error) {
      issues.add((error as Error).message);
      continue;
    }
    const name = cssName(entry, config.css.prefix, issues);
    const clash = cssValues(entry.token.$type, value)
      .map(([suffix]) => names.get(name + suffix))
      .find(Boolean);
    if (clash) {
      issues.add(`${where}: its CSS name --${name} is also ${clash}'s; give one of them a different WEB code syntax.`);
      continue;
    }
    cssValues(entry.token.$type, value).forEach(([suffix]) => names.set(name + suffix, where));
    const byMode = new Map<string, unknown>();
    for (const mode of modes) {
      try {
        const v = resolver.resolve(entry, mode);
        if (!sameValue(v, value)) byMode.set(mode, v);
      } catch (error) {
        issues.add(`${(error as Error).message} (mode ${mode})`);
      }
    }
    resolved.push({ entry, name, value, modes: byMode });
  }

  const files: OutputFile[] = [];
  if (config.outputs.css) {
    const block = (selector: string, items: [string, string][]) =>
      `${selector} {\n${items.map(([n, v]) => `  --${n}: ${v};`).join("\n")}\n}\n`;
    const declarations = (r: Resolved, value: unknown) =>
      cssValues(r.entry.token.$type, value).map(([suffix, v]): [string, string] => [r.name + suffix, v]);
    const blocks = [block(config.css.selector, resolved.flatMap((r) => declarations(r, r.value)))];
    for (const mode of modes) {
      const items = resolved
        .filter((r) => r.modes.has(mode))
        .flatMap((r) => {
          const base = new Map(declarations(r, r.value));
          return declarations(r, r.modes.get(mode)).filter(([n, v]) => base.get(n) !== v);
        });
      if (items.length > 0) blocks.push(block(config.css.modeSelector.replaceAll("{mode}", kebab(mode)), items));
    }
    files.push({ path: config.outputs.css, content: `/* ${HEADER} */\n\n${blocks.join("\n")}` });
  }

  if (config.outputs.module) {
    const object: Record<string, unknown> = {};
    const modeObjects: Record<string, Record<string, unknown>> = {};
    for (const r of resolved) {
      const type = r.entry.token.$type;
      if (!setPath(object, outPath(r.entry), moduleValue(type, r.value))) {
        issues.add(`${r.entry.path.join(".")}: its module path ${outPath(r.entry).join(".")} clashes with another token's.`);
        continue;
      }
      for (const [mode, value] of r.modes) {
        setPath((modeObjects[mode] ??= {}), outPath(r.entry), moduleValue(type, value));
      }
    }
    if (Object.keys(modeObjects).length > 0) object["$modes"] = modeObjects;
    const json = JSON.stringify(object, null, 2);
    const doc = "/** Design tokens: px and ms as numbers; $modes holds what differs in each other mode. */";
    const path = config.outputs.module;
    if (path.endsWith(".ts")) {
      files.push({ path, content: `// ${HEADER}\n\n${doc}\nexport const tokens = ${json} as const;\n` });
    } else {
      files.push({ path, content: `// ${HEADER}\n\n${doc}\nexport const tokens = ${json};\n` });
      files.push({
        path: path.replace(/\.(m?)js$/, ".d.$1ts"),
        content: `// ${HEADER}\n\n${doc}\nexport declare const tokens: ${json};\n`,
      });
    }
  }
  return files;
}
